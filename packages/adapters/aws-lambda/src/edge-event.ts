/**
 * The parts of a CloudFront origin-request event (Lambda@Edge) the adapter reads, and the response it generates.
 * Defined here, structurally, so the package needs no `@types/aws-lambda`; a full `CloudFrontRequestEvent` is
 * assignable.
 */

/** CloudFront's header map: lowercase names, each with one `{ key, value }` per value in the request. */
export type CloudFrontHeaders = Readonly<Record<string, readonly { readonly key?: string | undefined; readonly value: string }[] | undefined>>;

/** `Records[0].cf.request` of an origin-request event. */
export interface CloudFrontRequest {
  /** The viewer's IP address, as CloudFront saw the connection. Visitors can't set it. */
  readonly clientIp: string;
  readonly method: string;
  /** The path, as the viewer sent it (not decoded). */
  readonly uri: string;
  /** The query string without `?`, as the viewer sent it; empty when there is none. */
  readonly querystring: string;
  /** The headers the behaviour's origin request policy forwards, plus the CloudFront headers it adds. */
  readonly headers: CloudFrontHeaders;
}

/** An origin-request event: `Records[0].cf` holds the request and the distribution it came through. */
export interface CloudFrontRequestEvent {
  readonly Records: readonly {
    readonly cf: {
      readonly config: {
        /** The distribution's own hostname, like `d111111abcdef8.cloudfront.net`. */
        readonly distributionDomainName?: string | undefined;
        readonly eventType?: string | undefined;
      };
      readonly request: CloudFrontRequest;
    };
  }[];
}

/** A response generated by an origin-request function: CloudFront returns it without contacting the origin. */
export interface CloudFrontResultResponse {
  /** The status code, as a string (`'200'`). */
  readonly status: string;
  readonly statusDescription?: string;
  /** Lowercase names, one `{ key, value }` per value: each `Set-Cookie` is its own entry under `set-cookie`. */
  readonly headers: Readonly<Record<string, readonly { readonly key: string; readonly value: string }[]>>;
  readonly body: string;
  readonly bodyEncoding: 'text' | 'base64';
}
